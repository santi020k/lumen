import { mkdir, readdir, readFile, unlink, writeFile } from 'node:fs/promises'
import { join, resolve } from 'node:path'

import sharp from 'sharp'

const root = resolve(import.meta.dirname, '../../..')
const check = process.argv.includes('--check')
const stale = []

const output = async (path, content) => {
  if (!check) {
    await writeFile(path, content)

    return
  }

  const actual = await readFile(path).catch(() => Buffer.from(''))
  const expected = Buffer.isBuffer(content) ? content : Buffer.from(content)

  if (!actual.equals(expected)) stale.push(path)
}

const entries = []
const regions = []
const androidRegions = new Map()
const artwork = new Map()
const android = join(root, 'packages/compose/src/main/res/drawable-nodpi')
const apple = join(root, 'packages/swift/Sources/LumenUI/Resources/LumenFlags.xcassets')

await mkdir(android, { recursive: true })

for (const file of await readdir(android)) {
  if (!check && /^lumen_flag_[a-z]{2}\.png$/.test(file)) await unlink(join(android, file))
}

await mkdir(apple, { recursive: true })

await output(join(apple, 'Contents.json'), JSON.stringify({ info: { author: 'xcode', version: 1 } }, null, 2) + '\n')

for (const file of (await readdir(join(root, 'flags/svg'))).sort()) {
  const region = ({ 'sh-ac.svg': 'ac', 'sh-ta.svg': 'ta' })[file] ?? file.slice(0, -4)

  if (!/^[a-z]{2}$/.test(region)) continue

  const buffer = await sharp(await readFile(join(root, 'flags/svg', file)))
    .resize(64, 48).png({ palette: true, colors: 128 }).toBuffer()

  regions.push(region)

  entries.push(`  ${JSON.stringify(region.toUpperCase())}: ${JSON.stringify('data:image/png;base64,' + buffer.toString('base64'))}`)

  const key = buffer.toString('base64')
  const resource = artwork.get(key) ?? region

  androidRegions.set(region, resource)

  if (!artwork.has(key)) {
    artwork.set(key, region)

    await output(join(android, `lumen_flag_${region}.png`), buffer)
  }

  const asset = join(apple, `lumen-flag-${region}.imageset`)

  await mkdir(asset, { recursive: true })

  await output(join(asset, `${region}.png`), buffer)

  await output(join(asset, 'Contents.json'), JSON.stringify({ images: [{ filename: `${region}.png`, idiom: 'universal' }], info: { author: 'xcode', version: 1 } }, null, 2) + '\n')
}

await output(join(root, 'packages/core/src/phone-flags.generated.ts'), `// Generated by scripts/generate-phone-flags.mjs. Do not edit.\n// Artwork: flag-icons 7.5.0, MIT; see flags/LICENSE.\nexport const lumenPhoneFlagSources: Readonly<Record<string, string>> = {\n${entries.join(',\n')}\n}\n`)

for (const folder of ['core', 'react-native', 'swift', 'compose']) {
  await output(join(root, `packages/${folder}/PHONE_FLAG_LICENSE.txt`), await readFile(join(root, 'flags/LICENSE')))
}

await output(join(root, 'packages/compose/src/main/kotlin/com/santi020k/lumen/PhoneFlags.generated.kt'), `// Generated by scripts/generate-phone-flags.mjs.
package com.santi020k.lumen

internal val lumenPhoneFlagResources = mapOf(
${regions.map(region => `    "${region.toUpperCase()}" to R.drawable.lumen_flag_${androidRegions.get(region)}`).join(',\n')}
)
`)

await output(join(root, 'packages/swift/Sources/LumenUI/PhoneFlags.generated.swift'), `// Generated by scripts/generate-phone-flags.mjs.
let lumenPhoneFlagRegions: Set<String> = [
${regions.map(region => `    "${region.toUpperCase()}"`).join(',\n')}
]
`)

await mkdir(join(root, 'packages/compose/src/main/res/raw'), { recursive: true })

await output(join(root, 'packages/compose/src/main/res/raw/lumen_phone_flag_license.txt'), await readFile(join(root, 'flags/LICENSE')))

await output(join(root, 'packages/swift/Sources/LumenUI/Resources/PhoneFlagLicense.txt'), await readFile(join(root, 'flags/LICENSE')))

if (check) {
  const expectedResources = new Set([...artwork.values()].map(region => `lumen_flag_${region}.png`))

  for (const file of await readdir(android)) {
    if (/^lumen_flag_[a-z]{2}\.png$/.test(file) && !expectedResources.has(file)) stale.push(join(android, file))
  }
}

if (stale.length > 0) throw new Error(`Phone artwork is stale. Run pnpm run generate:phone-flags.\n${stale.join('\n')}`)

console.log(`${check ? 'Checked' : 'Generated'} ${entries.length} shared phone flags.`)
