// Builds the single stylesheet bundled by the lumen-dioxus crate.
//
// Source: the generated standalone stylesheet in packages/core/styles/lumen.css, with its
// local @import files inlined because Dioxus Native (Blitz) loads one embedded stylesheet.
// Adapter change: Blitz does not honor `appearance: none` on form controls yet, so
// lumen-dioxus renders Checkbox and Switch as ARIA buttons. Every `:checked` and
// `:indeterminate` rule for those two controls gains an `[aria-checked]` twin, so the
// canonical CSS stays the single source of truth.
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { readCssNodes, splitCssSelectors } from './lib/css-source.mjs'

const root = fileURLToPath(new URL('../', import.meta.url))
const check = process.argv.includes('--check')
const sourcePath = join(root, 'packages/core/styles/lumen.css')
const outputPath = join(root, 'packages/dioxus/assets/lumen.css')
const banner = '/* Generated by scripts/generate-dioxus-css.mjs from packages/core/styles/lumen.css; do not edit. */\n'

export const ariaStateAliases = [
  ['.ui-checkbox:checked', '.ui-checkbox[aria-checked="true"]'],
  ['.ui-checkbox:indeterminate', '.ui-checkbox[aria-checked="mixed"]'],
  ['.ui-switch:checked', '.ui-switch[aria-checked="true"]']
]

// A <button> carries user-agent padding and font that an <input> does not.
const adapterRules = `
button.ui-checkbox,
button.ui-switch {
  padding: 0;
  font: inherit;
  flex-shrink: 0;
}
`

const parseImport = statement => {
  const prefix = '@import "'
  const trimmed = statement.trim()

  if (!trimmed.startsWith(prefix) || !trimmed.endsWith('";')) return null

  const path = trimmed.slice(prefix.length, -2)

  return path.includes('"') ? null : path
}

/** Inline local `@import "./file.css";` statements, one level of files at a time. */
export const inlineImports = async (file, seen = new Set()) => {
  if (seen.has(file)) throw new Error(`Cyclic CSS import: ${file}`)

  const next = new Set([...seen, file])
  const source = await readFile(file, 'utf8')
  const lines = []

  for (const line of source.split('\n')) {
    const path = parseImport(line)

    if (path === null) {
      lines.push(line)

      continue
    }

    if (!path.startsWith('./')) throw new Error(`Only local CSS imports can be inlined: ${path}`)

    lines.push(await inlineImports(resolve(dirname(file), path), next))
  }

  return lines.join('\n')
}

const aliasSelectors = selectors => {
  const extra = []

  for (const selector of selectors) {
    for (const [from, to] of ariaStateAliases) {
      if (selector.includes(from)) extra.push(selector.replaceAll(from, to))
    }
  }

  return extra.filter(selector => !selectors.includes(selector))
}

/** Return the transformed CSS, or null when nothing in `source` needed an alias. */
export const addAriaStateAliases = source => {
  let changed = false

  const parts = readCssNodes(source).map(node => {
    if (node.body === null) return node.text

    if (node.header.startsWith('@')) {
      const inner = addAriaStateAliases(node.body)

      if (inner === null) return node.text

      changed = true

      return `${node.header} {\n${inner}\n}`
    }

    const selectors = splitCssSelectors(node.header)
    const extra = aliasSelectors(selectors)
    const nested = node.body.includes('{') ? addAriaStateAliases(node.body) : null

    if (!extra.length && nested === null) return node.text

    changed = true

    const header = extra.length ? [...selectors, ...extra].join(',\n') : node.header

    return `${header} {${nested ?? node.body}}`
  })

  return changed ? parts.join('\n\n') : null
}

export const buildDioxusCss = async () => {
  const flattened = await inlineImports(sourcePath)
  const aliased = addAriaStateAliases(flattened)

  if (aliased === null) throw new Error('Expected checkbox and switch state rules in the standalone CSS.')

  return `${banner}${aliased}\n${adapterRules}`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const css = await buildDioxusCss()

  if (check) {
    const current = await readFile(outputPath, 'utf8').catch(() => '')

    if (current !== css) {
      console.error('packages/dioxus/assets/lumen.css is stale. Run `pnpm run generate:dioxus-css`.')

      process.exitCode = 1
    }
  } else {
    await writeFile(outputPath, css)

    console.log(`Wrote packages/dioxus/assets/lumen.css (${css.length} bytes).`)
  }
}
