import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

import { readCssNodes } from './lib/css-source.mjs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const check = process.argv.includes('--check')
const sourcePath = path.join(root, 'packages/lumen/styles.css')

const outputPaths = [
  'packages/lumen/styles/critical.css',
  'packages/astro/styles/critical.css',
  'packages/react/styles/critical.css',
  'packages/elements/styles/critical.css'
]

const criticalSelectors = [
  // Select chevron variables inherit from these direction scopes.
  '[dir="ltr"]',
  '[dir="rtl"]',
  '.ui-alert',
  '.ui-badge',
  '.ui-button',
  '.ui-calendar',
  '.ui-card',
  '.ui-checkbox',
  '.ui-combobox',
  '.ui-data-table',
  'lumen-date-picker.ui-date-picker-field',
  '.ui-dialog',
  '.ui-field',
  '.ui-input',
  '.ui-label',
  '.ui-progress',
  '.ui-select',
  '.ui-skeleton',
  '.ui-spinner',
  '.ui-table',
  '.ui-tabs',
  '.ui-textarea',
  '.ui-toast',
  '.ui-tooltip'
]

const selectCriticalRules = source => {
  const selected = []

  for (const node of readCssNodes(source)) {
    const { header, body, text } = node

    if (body === null) {
      if (header.startsWith('@layer ')) selected.push(`${header};`)

      continue
    }

    if (header === '@layer lumen.tokens' || header === '@layer lumen.base') {
      selected.push(text.trim())
    } else if (header.startsWith('@')) {
      const nested = selectCriticalRules(body)

      if (nested) selected.push(`${header} {\n${nested}\n}`)
    } else if (criticalSelectors.some(selector => header.includes(selector))) {
      selected.push(text.trim())
    }
  }

  return selected.join('\n\n')
}

const source = await readFile(sourcePath, 'utf8')
const selected = selectCriticalRules(source)
const output = `/* Generated by scripts/generate-critical-web-css.mjs. */\n${selected}\n`

if (!selected.includes('.ui-button') || !selected.includes('.ui-data-table')) {
  throw new Error('Critical CSS generation omitted required component rules.')
}

if (selected.includes('.ui-animated-portrait')) {
  throw new Error('Critical CSS generation included a non-critical component.')
}

for (const relativePath of outputPaths) {
  const outputPath = path.join(root, relativePath)

  if (check) {
    const current = await readFile(outputPath, 'utf8')

    if (current !== output) throw new Error(`${relativePath} is stale. Run pnpm run generate:critical-web-css.`)
  } else {
    await mkdir(path.dirname(outputPath), { recursive: true })

    await writeFile(outputPath, output)
  }
}

console.log(`${check ? 'Checked' : 'Generated'} ${outputPaths.length} critical CSS entries (${Buffer.byteLength(output)} bytes).`)
