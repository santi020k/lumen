const writeGeneratedFile = async (relativePath, content) => {
  const path = join(repositoryRoot, relativePath)
  const output = content.endsWith('\n') ? content : `${content}\n`

  if (checkOnly) {
    const current = await readFile(path, 'utf8').catch(() => '')

    if (current !== output) throw new Error(`${relativePath} is stale.`)

    return
  }

  await mkdir(dirname(path), { recursive: true })

  const temporaryPath = `${path}.${process.pid}.tmp`

  try {
    await writeFile(temporaryPath, output, 'utf8')

    await rename(temporaryPath, path)
  } finally {
    await unlink(temporaryPath).catch(() => {})
  }
}

const illustrations = await readCatalog()

const outputs = [
  ['packages/core/src/illustrations.generated.ts', typescript(illustrations)],
  ['packages/react-native/src/illustrations.generated.ts', typescript(illustrations, false)],
  ['packages/swift/Sources/LumenUI/Illustrations.generated.swift', swift(illustrations)],
  [
    'packages/compose/src/main/kotlin/com/santi020k/lumen/Illustrations.generated.kt',
    kotlin(illustrations)
  ]
]

await Promise.all(outputs.map(([path, content]) => writeGeneratedFile(path, content)))

process.stdout.write(
  `lumen-platform-graphics: ${checkOnly ? 'verified' : 'generated'} ${outputs.length} outputs\n`
)
