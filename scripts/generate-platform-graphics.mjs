const kotlinElement = element => {
  if (element.kind === 'circle') return `Circle(${element.cx}f, ${element.cy}f, ${element.r}f)`

  if (element.kind === 'rounded-rect') {
    return `RoundedRect(${element.x}f, ${element.y}f, ${element.width}f, ${element.height}f, ${element.radius}f)`
  }

  return `${pascalCase(element.kind)}(listOf(${element.points.map(point => `${point}f`).join(', ')}))`
}

