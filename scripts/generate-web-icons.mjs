import assert from 'node:assert/strict'
import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

import { icons } from '@lucide/icons'

const root = resolve(import.meta.dirname, '..')
const catalog = JSON.parse(await readFile(resolve(root, 'icons/lumen.icons.json'), 'utf8'))
const pack = catalog.packs.find(candidate => candidate.name === 'interface')

assert.equal(pack?.source, 'lucide')

assert.equal(pack?.selection, 'all')

const exportsByName = new Map(Object.keys(icons).map(name => [name, name]))

for (const [alias, target] of Object.entries(pack.aliases ?? {})) {
  const targetName = Object.keys(icons).find(name => icons[name].name === target)
  const aliasName = alias.split('-').map(part => part.charAt(0).toUpperCase() + part.slice(1)).join('')

  assert.ok(targetName, `Unknown static icon alias target: ${target}`)

  if (!exportsByName.has(aliasName)) exportsByName.set(aliasName, `${targetName} as ${aliasName}`)
}

const names = [...exportsByName.keys()].sort()

assert.ok(!names.includes('Icon'), 'Static icon definitions must not shadow the React renderer.')

const output = `// Generated by scripts/generate-web-icons.mjs from the canonical interface catalog.\n// Individual re-exports allow browser bundlers to retain only the requested definitions.\nexport {\n${names.map(name => `  ${exportsByName.get(name)}`).join(',\n')}\n} from '@lucide/icons'\n`
const path = resolve(root, 'packages/core/src/icon-data.generated.ts')

if (process.argv.includes('--check')) {
  assert.equal(await readFile(path, 'utf8'), output, 'Run pnpm run generate:platform-icons')
} else {
  await writeFile(path, output)
}

process.stdout.write(`${process.argv.includes('--check') ? 'Checked' : 'Generated'} ${names.length} static web icon definitions.\n`)
