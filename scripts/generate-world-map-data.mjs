const writeGeneratedFile = async (path, content) => {
  const output = content.endsWith('\n') ? content : `${content}\n`

  if (checkOnly) {
    const current = await readFile(path, 'utf8').catch(() => '')

    if (current !== output) throw new Error(`${path.slice(repoRoot.length + 1)} is stale. Run 'pnpm run generate:world-map-data'.`)

    return
  }

  await mkdir(dirname(path), { recursive: true })

  const temporaryPath = `${path}.${process.pid}.tmp`

  try {
    await writeFile(temporaryPath, output, 'utf8')

    await rename(temporaryPath, path)
  } finally {
    await unlink(temporaryPath).catch(() => {})
  }
}

const main = async () => {
  const source = JSON.parse(await readFile(sourcePath, 'utf8'))

  if (!Array.isArray(source.countries) || source.countries.length === 0) {
    throw new TypeError('Expected a non-empty "countries" array in maps/world-map.source.json.')
  }

  const ids = new Set()

  for (const country of source.countries) {
    if (ids.has(country.id)) throw new Error(`Duplicate country id "${country.id}" in maps/world-map.source.json.`)

    ids.add(country.id)
  }

  const body = source.countries.map(renderCountry).join(',\n')
  const output = `${header}${body}\n]\n`

  await writeGeneratedFile(outputPath, output)

  process.stdout.write(
    `lumen-world-map-data: ${checkOnly ? 'verified' : 'generated'} ${source.countries.length} countries\n`
  )
}

await main()
