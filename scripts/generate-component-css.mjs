import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { normalizeCssFamily, partitionComponentCss } from './lib/component-css.mjs'
import { readCssNodes } from './lib/css-source.mjs'

const root = fileURLToPath(new URL('../', import.meta.url))
const check = process.argv.includes('--check')
const read = path => readFile(join(root, path), 'utf8')
const metadata = JSON.parse(await read('registry/web-css.json'))
const canonical = await read('packages/lumen/styles.css')
const worldMap = await read('packages/lumen/styles/world-map.css')
const shared = partitionComponentCss([worldMap, canonical])
const astro = partitionComponentCss([await read('packages/astro/styles/lumen.css')])
const banner = '/* Generated by scripts/generate-component-css.mjs; edit canonical CSS and registry/web-css.json. */\n'
// A component chunk can precede a consumer's Tailwind stylesheet in Astro's graph.
// Establish the complete public order on first encounter, before Tailwind creates base.
const layerOrder = readCssNodes(await read('packages/lumen/layers.css')).map(node => node.text.trim()).join('\n') + '\n'
const outputs = new Map()
const slug = name => name.replaceAll(/([a-z\d])([A-Z])/g, '$1-$2').replaceAll(/([A-Z])([A-Z][a-z])/g, '$1-$2').toLowerCase()

const collectParts = (name, visiting = new Set()) => {
  if (visiting.has(name)) throw new Error(`Cyclic component style dependency: ${name}`)

  const entry = metadata.components[name]

  if (!entry) throw new Error(`Unknown component style dependency: ${name}`)

  const next = new Set([...visiting, name])

  return new Set([...entry.parts.map(normalizeCssFamily), ...entry.dependencies.flatMap(dependency => [...collectParts(dependency, next)])])
}

const componentFiles = (await readdir(join(root, 'packages/astro/components')))
  .filter(name => name.endsWith('.astro')).map(name => name.slice(0, -6)).sort()

if (JSON.stringify(componentFiles) !== JSON.stringify(Object.keys(metadata.components).sort())) {
  throw new Error('registry/web-css.json must cover the complete public Astro component catalog.')
}

outputs.set('packages/core/styles/foundation.css', banner + layerOrder + shared.foundation + '\n')

for (const [entry, rules] of Object.entries(shared.appearances)) {
  const path = `styles/${entry}.css`

  outputs.set(`packages/core/${path}`, banner + layerOrder + rules.join('\n\n') + '\n')

  for (const adapter of ['lumen', 'astro', 'react', 'elements']) {
    outputs.set(`packages/${adapter}/${path}`, `${banner}${layerOrder}@import "@santi020k/lumen-core/${path}";\n`)
  }
}

// Full CSS uses relative imports so it also works outside a package-aware bundler.
outputs.set('packages/core/styles/lumen.css', banner + canonical.replaceAll('@import "./styles/', '@import "./'))

for (const theme of ['paper', 'field']) {
  const path = `styles/themes/${theme}.css`

  outputs.set(`packages/core/${path}`, banner + await read(`packages/lumen/${path}`))

  for (const adapter of ['astro', 'react', 'elements']) {
    outputs.set(`packages/${adapter}/${path}`, `${banner}${layerOrder}@import "@santi020k/lumen-core/${path}";\n`)
  }
}

outputs.set('packages/core/styles/world-map.css', banner + worldMap)

for (const [source, target] of [
  ['packages/lumen/styles/critical.css', 'critical.css'], ['packages/lumen/styles/motion.css', 'motion.css'],
  ['packages/lumen/layers.css', 'layers.css'], ['packages/lumen/tailwind.css', 'tailwind.css']
]) outputs.set(`packages/core/styles/${target}`, banner + await read(source))

for (const [name, css] of shared.parts) outputs.set(`packages/core/styles/parts/${name}.css`, banner + layerOrder + css + '\n')

for (const [name, css] of astro.parts) outputs.set(`packages/astro/styles/parts/${name}.css`, banner + layerOrder + css + '\n')

const manifest = {}

for (const name of componentFiles) {
  const key = slug(name)
  const families = [...collectParts(name)]

  for (const family of families) {
    if (!shared.families.has(family) && !astro.families.has(family)) throw new Error(`${name} references missing CSS part ${family}`)
  }

  const requiredParts = new Set(families.flatMap(family => shared.families.get(family) ?? []))
  const requiredExtras = new Set(families.flatMap(family => astro.families.get(family) ?? []))
  const parts = [...shared.parts.keys()].filter(part => requiredParts.has(part))
  const extras = [...astro.parts.keys()].filter(part => requiredExtras.has(part))
  const imports = parts.map(part => `../parts/${part}.css`)

  outputs.set(`packages/core/styles/components/${key}.css`, banner + layerOrder + imports.map(path => `@import "${path}";`).join('\n') + '\n')

  if (name === 'Toast') {
    // A URL asset avoids Astro eagerly collecting CSS from a dynamic script import.
    outputs.set('packages/astro/styles/runtime/toast.css', banner + layerOrder
      + parts.map(part => shared.parts.get(part)).join('\n\n') + '\n')
  }

  for (const adapter of ['lumen', 'astro', 'react', 'elements']) {
    const extraImports = adapter === 'astro' ? extras.map(part => `@import "../parts/${part}.css";`) : []

    outputs.set(`packages/${adapter}/styles/components/${key}.css`, `${banner}${layerOrder}@import "@santi020k/lumen-core/styles/components/${key}.css";\n${extraImports.join('\n')}\n`)
  }

  manifest[name] = { stylesheet: `styles/components/${key}.css`, parts, dependencies: metadata.components[name].dependencies }
}

outputs.set('packages/core/styles/manifest.json', JSON.stringify(manifest, null, 2) + '\n')

for (const adapter of ['lumen', 'astro', 'react', 'elements']) {
  outputs.set(`packages/${adapter}/styles/foundation.css`, `${banner}${layerOrder}@import "@santi020k/lumen-core/styles/foundation.css";\n`)
}

// Remove obsolete generated parts after ownership changes, while protecting handwritten files.
const managedDirectories = [
  'packages/core/styles', 'packages/astro/styles/parts', 'packages/astro/styles/runtime',
  ...['lumen', 'astro', 'react', 'elements'].map(adapter => `packages/${adapter}/styles/components`)
]

for (const directory of managedDirectories) {
  await mkdir(join(root, directory), { recursive: true })

  for (const entry of await readdir(join(root, directory), { recursive: true, withFileTypes: true })) {
    if (!entry.isFile()) continue

    const absolute = join(entry.parentPath, entry.name)
    const path = absolute.slice(root.length)

    if (outputs.has(path)) continue

    if (!(await readFile(absolute, 'utf8')).startsWith(banner)) throw new Error(`Unexpected handwritten file in generated CSS directory: ${path}`)

    if (check) throw new Error(`Obsolete generated CSS: ${path}. Run pnpm run generate:component-css.`)

    await rm(absolute)
  }
}

for (const [path, source] of outputs) {
  const content = source.trimEnd() + '\n'

  if (check) {
    if (await read(path) !== content) throw new Error(`${path} is stale. Run pnpm run generate:component-css.`)
  } else {
    await mkdir(dirname(join(root, path)), { recursive: true })

    await writeFile(join(root, path), content)
  }
}

process.stdout.write(`${check ? 'Checked' : 'Generated'} ${outputs.size} CSS assets for ${componentFiles.length} public components.\n`)
