import { readFile } from 'node:fs/promises'

import { mapSanti020kSiteColors, readSanti020kSiteColors } from './santi020k-site-colors.mjs'

const readingNames = ['paper', 'field']
const schemes = ['light', 'dark']
const camel = name => name.replaceAll(/-([a-z])/gu, (_, letter) => letter.toUpperCase())
const pascal = name => name[0].toUpperCase() + name.slice(1)
const generated = '// Generated by scripts/generate-platform-tokens.mjs.'

// Source channels use the same opaque HSL format as the optional web stylesheets.
const toHex = (value, path) => {
  const channels = typeof value === 'string' && /^(\d{1,3}) (\d{1,3})% (\d{1,3})%$/u.exec(value)

  if (!channels) throw new Error(`Invalid opaque HSL color at ${path}`)

  const [, hue, saturation, lightness] = channels.map(Number)

  if (hue > 360 || saturation > 100 || lightness > 100) throw new Error(`Invalid HSL range at ${path}`)

  const light = lightness / 100
  const amplitude = saturation / 100 * Math.min(light, 1 - light)

  const channel = offset => {
    const angle = (offset + hue / 30) % 12
    const unit = light - amplitude * Math.max(-1, Math.min(angle - 3, 9 - angle, 1))

    return Math.round(unit * 255).toString(16).padStart(2, '0')
  }

  return `#${[0, 8, 4].map(channel).join('').toUpperCase()}`
}

const nativeColors = (roles, palette, name) => {
  if (Object.keys(palette).some(key => !roles.includes(key))) throw new Error(`Unknown color role in ${name}`)

  return Object.fromEntries(roles.map(role => [camel(role), toHex(palette[role], `${name}.${role}`)]))
}

export const resolveNamedThemes = (source, site) => {
  const roles = Object.keys(source.color.light).filter(role => !role.startsWith('$'))
  const readings = source.$extensions['com.santi020k.lumen'].readingThemes
  const themes = {}

  if (!readings || Object.keys(readings).some(name => !readingNames.includes(name))) throw new Error('Unknown reading theme')

  for (const name of readingNames) {
    const recipe = readings[name]

    if (!recipe) throw new Error(`Missing reading theme: ${name}`)

    const { radii, serifHeadings } = recipe

    if (typeof serifHeadings !== 'boolean' || !radii || Object.keys(radii).length !== 3
      || ['sm', 'md', 'lg'].some(key => !Number.isFinite(radii[key]) || radii[key] < 0)) throw new Error(`Invalid ${name} appearance`)

    const colors = Object.fromEntries(schemes.map(scheme => {
      const palette = recipe[scheme]

      if (!palette || Object.hasOwn(palette, 'brand')) throw new Error(`Expected ${name}.${scheme} colors with brand derived from brand-solid`)

      return [scheme, nativeColors(roles, { ...palette, brand: palette['brand-solid'] }, `${name}.${scheme}`)]
    }))

    themes[name] = { ...colors, radii, serifHeadings, inkActions: false, chartBrand: null, onSuccess: null, statusText: null }
  }

  const chartBrand = {}

  const colors = Object.fromEntries(schemes.map(scheme => {
    const { 'ui-website-brand': chart, ...palette } = mapSanti020kSiteColors(site[scheme], scheme)

    chartBrand[scheme] = toHex(chart, `santi020k.${scheme}.chartBrand`)

    return [scheme, nativeColors(roles, {
      ...palette,
      'on-brand': source.color[scheme]['on-brand'].$extensions['com.santi020k.lumen'].cssValue,
      'on-danger': scheme === 'dark' ? palette.canvas : '0 0% 100%'
    }, `santi020k.${scheme}`)]
  }))

  // Native success buttons use a solid status fill. White works on the brand fill but
  // fails contrast on both site greens. Use black in light mode and the site canvas in dark.
  const onSuccess = { light: '#000000', dark: colors.dark.canvas }

  themes.santi020k = { ...colors, radii: null, serifHeadings: false, inkActions: true, chartBrand, onSuccess, statusText: { light: colors.light.ink } }

  return themes
}

const updateBlock = (source, name, values) => {
  const open = `    /* BEGIN:generated-${name} */\n`
  const close = `\n    /* END:generated-${name} */`
  const start = source.indexOf(open)
  const end = source.indexOf(close, start + open.length)

  if (start < 0 || end < 0) throw new Error(`Missing theme CSS markers: ${name}`)

  return source.slice(0, start + open.length) + values.join('\n') + source.slice(end)
}

const readingCss = (css, name, recipe) => {
  for (const scheme of schemes) {
    css = updateBlock(css, scheme, Object.entries(recipe[scheme]).map(([role, hsl]) => `    --_${name}-${role}: ${hsl};`))
  }

  return updateBlock(css, 'radii', Object.entries(recipe.radii).map(([size, value]) => {
    const suffix = size === 'md' ? '' : `-${size}`

    return `    --ui-radius${suffix}: ${value / 16}rem;`
  }))
}

const swiftColor = hex => {
  const [red, green, blue] = [1, 3, 5].map(i => (Number.parseInt(hex.slice(i, i + 2), 16) / 255).toFixed(6))

  return `Color(red: ${red}, green: ${green}, blue: ${blue})`
}

const kotlinColor = hex => `Color(0xFF${hex.slice(1)})`

const paletteArgs = (colors, separator, color) =>
  Object.entries(colors).map(([key, hex]) => `            ${key}${separator}${color(hex)}`).join(',\n')

const swiftTheme = ([name, theme]) => {
  const palette = scheme => `LumenColorPalette(\n${paletteArgs(theme[scheme], ': ', swiftColor)}\n        )`
  const radii = theme.radii ? `.init(sm: ${theme.radii.sm}, md: ${theme.radii.md}, lg: ${theme.radii.lg})` : 'nil'
  const optionalColor = (values, scheme) => values?.[scheme] ? swiftColor(values[scheme]) : 'nil'

  return `    static let ${name} = LumenNamedTheme(\n        light: ${palette('light')},\n        dark: ${palette('dark')},\n        radii: ${radii}, serifHeadings: ${theme.serifHeadings}, inkActions: ${theme.inkActions},\n        lightChartBrand: ${optionalColor(theme.chartBrand, 'light')}, darkChartBrand: ${optionalColor(theme.chartBrand, 'dark')},\n        lightOnSuccess: ${optionalColor(theme.onSuccess, 'light')}, darkOnSuccess: ${optionalColor(theme.onSuccess, 'dark')},\n        lightStatusText: ${optionalColor(theme.statusText, 'light')}, darkStatusText: ${optionalColor(theme.statusText, 'dark')}\n    )`
}

const kotlinTheme = ([name, theme]) => {
  const palette = scheme => `LumenColorPalette(\n${paletteArgs(theme[scheme], ' = ', kotlinColor)}\n        )`
  const radii = theme.radii ? `LumenThemeRadii(sm = ${theme.radii.sm}f, md = ${theme.radii.md}f, lg = ${theme.radii.lg}f)` : 'null'
  const optionalColor = (values, scheme) => values?.[scheme] ? kotlinColor(values[scheme]) : 'null'

  return `    val ${pascal(name)} = LumenNamedTheme(\n        light = ${palette('light')},\n        dark = ${palette('dark')},\n        radii = ${radii}, serifHeadings = ${theme.serifHeadings}, inkActions = ${theme.inkActions},\n        lightChartBrand = ${optionalColor(theme.chartBrand, 'light')}, darkChartBrand = ${optionalColor(theme.chartBrand, 'dark')},\n        lightOnSuccess = ${optionalColor(theme.onSuccess, 'light')}, darkOnSuccess = ${optionalColor(theme.onSuccess, 'dark')},\n        lightStatusText = ${optionalColor(theme.statusText, 'light')}, darkStatusText = ${optionalColor(theme.statusText, 'dark')}\n    )`
}

export const namedThemeOutputs = async (source, root) => {
  const themes = Object.entries(resolveNamedThemes(source, await readSanti020kSiteColors()))
  const readings = source.$extensions['com.santi020k.lumen'].readingThemes

  const css = await Promise.all(readingNames.map(async name => {
    const path = `packages/lumen/styles/themes/${name}.css`

    return [path, readingCss(await readFile(`${root}/${path}`, 'utf8'), name, readings[name])]
  }))

  return [
    ...css,
    ...themes.map(([name, theme]) => [`packages/react-native/src/themes/${name}.generated.ts`, `${generated}\nexport const ${name}Theme = ${JSON.stringify(theme, null, 2)} as const\n`]),
    ['packages/swift/Sources/LumenUI/NamedThemes.generated.swift', `${generated}\nimport SwiftUI\n\npublic extension LumenNamedTheme {\n${themes.map(swiftTheme).join('\n\n')}\n}\n`],
    ['packages/compose/src/main/kotlin/com/santi020k/lumen/NamedThemes.generated.kt', `${generated}\npackage com.santi020k.lumen\n\nimport androidx.compose.ui.graphics.Color\n\nobject LumenNamedThemes {\n${themes.map(kotlinTheme).join('\n\n')}\n}\n`]
  ]
}
