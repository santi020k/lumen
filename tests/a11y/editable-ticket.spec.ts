import { expect, test } from '@playwright/test'

test('ticket and listing preview, cancel, commit and undo with keyboard focus', async ({ page }) => {
  await page.goto('/docs/editable-ticket')
  const ticket = page.locator('lumen-editable-ticket')
  const edit = ticket.getByRole('button', { name: 'Edit venue', exact: true })
  await edit.focus()
  await page.keyboard.press('Enter')
  const input = ticket.getByRole('textbox', { name: 'Venue', exact: true })
  await expect(input).toBeFocused()
  await input.fill('South Hall')
  await expect(ticket.locator('[data-venue]')).toHaveText(['South Hall', 'South Hall'])
  await input.press('Escape')
  await expect(edit).toBeFocused()
  await expect(ticket.locator('[data-venue]')).toHaveText(['North Hall', 'North Hall'])
  await edit.press('Space')
  await input.fill('  South Hall  ')
  await input.press('Enter')
  await expect(edit).toBeFocused()
  await expect(ticket.locator('[data-venue]')).toHaveText(['South Hall', 'South Hall'])
  await ticket.getByRole('button', { name: 'Undo edit' }).click()
  await expect(ticket.locator('[data-venue]')).toHaveText(['North Hall', 'North Hall'])
  await expect(ticket.getByRole('button', { name: 'Edit event name' })).toBeFocused()
})
